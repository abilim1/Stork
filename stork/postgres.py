"""PostgreSQL persistence; shares validation and stock semantics with Store."""
from __future__ import annotations

import threading
from contextlib import contextmanager, nullcontext

from .storage import Store

# Both the app and migrator take this session lock: only one owns a database.
DATABASE_LOCK = 7349018765
SCHEMA = """
CREATE TABLE IF NOT EXISTS bars(symbol TEXT, time BIGINT, interval INTEGER, open DOUBLE PRECISION, high DOUBLE PRECISION, low DOUBLE PRECISION, close DOUBLE PRECISION, volume DOUBLE PRECISION, source TEXT, PRIMARY KEY(symbol,time,interval));
CREATE TABLE IF NOT EXISTS documents(key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS reports(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, created DOUBLE PRECISION, status TEXT, body TEXT, error TEXT);
CREATE TABLE IF NOT EXISTS positions(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, created DOUBLE PRECISION, quantity DOUBLE PRECISION, entry DOUBLE PRECISION, intent TEXT, reason TEXT, state TEXT DEFAULT 'open', exit DOUBLE PRECISION, history TEXT);
CREATE TABLE IF NOT EXISTS events(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, created DOUBLE PRECISION, kind TEXT, title TEXT, body TEXT);
CREATE TABLE IF NOT EXISTS ticks(sequence TEXT PRIMARY KEY, time DOUBLE PRECISION, price DOUBLE PRECISION, volume DOUBLE PRECISION);
CREATE INDEX IF NOT EXISTS reports_stock_id ON reports ((COALESCE(body::jsonb->>'symbol', 'US.MU')), id DESC);
CREATE INDEX IF NOT EXISTS positions_stock_id ON positions ((COALESCE(history::jsonb->0->>'symbol', 'US.MU')), id DESC);
CREATE INDEX IF NOT EXISTS ticks_stock_time ON ticks ((CASE WHEN strpos(sequence, ':') = 0 THEN 'US.MU' ELSE split_part(sequence, ':', 1) END), time DESC);
"""


def connect_database(conninfo):
    import psycopg
    from psycopg.rows import dict_row

    # Avoid transactions sitting open between browser polls; writes use explicit
    # transactions. Dead connections fail visibly rather than falling back to SQLite.
    db = psycopg.connect(conninfo, autocommit=True, row_factory=dict_row,
                         connect_timeout=10, application_name="stork",
                         options="-c search_path=public -c statement_timeout=30000 -c lock_timeout=10000",
                         keepalives=1, keepalives_idle=15, keepalives_interval=5,
                         keepalives_count=3, tcp_user_timeout=20000)
    try:
        if not db.execute("SELECT pg_try_advisory_lock(%s) AS acquired", (DATABASE_LOCK,)).fetchone()["acquired"]:
            raise RuntimeError("Another Stork instance or migration is using this database")
    except BaseException:
        db.close()
        raise
    return db


def create_schema(db):
    for statement in SCHEMA.split(";"):
        if statement.strip():
            db.execute(statement)


class PostgreSQLStore(Store):
    report_symbol_sql = "COALESCE(body::jsonb->>'symbol', 'US.MU')"
    position_symbol_sql = "COALESCE(history::jsonb->0->>'symbol', 'US.MU')"
    tick_symbol_sql = "(CASE WHEN strpos(sequence, ':') = 0 THEN 'US.MU' ELSE split_part(sequence, ':', 1) END)"

    def __init__(self, conninfo):
        self.lock = threading.RLock()
        self.db = connect_database(conninfo)
        try:
            with self.db.transaction():
                create_schema(self.db)
        except BaseException:
            self.db.close()
            raise

    def _execute(self, query, parameters=()):
        # Only fixed internal SQL uses '?' placeholders; user values remain bound.
        return self.db.execute(query.replace("?", "%s"), parameters)

    def _executemany(self, query, values):
        with self.db.cursor() as cursor:
            cursor.executemany(query.replace("?", "%s"), values)

    @contextmanager
    def _transaction(self):
        # Batch transaction commands over the SSH connection. A read still flushes
        # when its result is needed, while single-write commits take one round trip.
        with self.db.pipeline(), self.db.transaction():
            yield

    def _insert_id(self, query, parameters):
        return self._execute(query + " RETURNING id", parameters).fetchone()["id"]

    def _write(self):
        # A single SQL write is already atomic in autocommit mode. Avoid extra
        # BEGIN/COMMIT round trips for every received market tick.
        return nullcontext()
